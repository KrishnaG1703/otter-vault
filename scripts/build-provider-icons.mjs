// marks kept locally because Simple Icons no longer carries them: title and brand colour
const LOCAL = {
  openai: ['OpenAI', '412991'],
  amazonwebservices: ['Amazon Web Services', '232F3E'],
  slack: ['Slack', '4A154B'],
  groq: ['Groq', 'F55036'],
  google: ['Google', '4285F4']
};

const data = JSON.parse(readFileSync(join(source, 'data', 'simple-icons.json'), 'utf8'));
const list = Array.isArray(data) ? data : data.icons;
const slugOf = icon => icon.slug || icon.title.toLowerCase().replace(/\+/g, 'plus').replace(/\./g, 'dot').replace(/&/g, 'and')
  .normalize('NFD').replace(/[^a-z0-9]/g, '');
const { version } = JSON.parse(readFileSync(join(source, 'package.json'), 'utf8'));

const pathOf = (svg, slug) => {
  if ((svg.match(/<path /g) || []).length !== 1) throw new Error(`${slug}: expected one path`);
  const path = /<path d="([^"]+)"/.exec(svg)?.[1];
  if (!path || !/^[MmLlHhVvCcSsQqTtAaZz0-9.,\s-]+$/.test(path)) throw new Error(`${slug}: unexpected path data`);
  return path;
};

const icons = PROVIDERS.map(([slug, hosts]) => {
  if (LOCAL[slug]) {
    const svg = readFileSync(join('store', 'source', 'provider-icons', `${slug}.svg`), 'utf8');
    const [title, hex] = LOCAL[slug];
    return { slug, title, hex, path: pathOf(svg, slug), evenOdd: /fill-rule="evenodd"/.test(svg), hosts };
  }
  const meta = list.find(icon => slugOf(icon) === slug);
  if (!meta) throw new Error(`Simple Icons has no ${slug}`);
  return { slug, title: meta.title, hex: meta.hex, path: pathOf(readFileSync(join(source, 'icons', `${slug}.svg`), 'utf8'), slug), evenOdd: false, hosts };
});

const out = `// Generated by scripts/build-provider-icons.mjs from Simple Icons ${version} (CC0-1.0,
// https://simpleicons.org) and store/source/provider-icons/. Brand marks belong to their owners and
// only label which provider a shared key is for. Do not edit by hand.
export const PROVIDER_ICONS = [
${icons.map(icon => `  ${JSON.stringify(icon)}`).join(',\n')}
];

// The provider for a key's site, matching the host or any subdomain of it (never a lookalike).
export function iconForOrigin(origin) {
  let host = '';
  try { host = new URL(origin).hostname.toLowerCase(); } catch { return null; }
  return PROVIDER_ICONS.find(icon => icon.hosts.some(known => host === known || host.endsWith(\`.\${known}\`))) || null;
}
`;
writeFileSync('extension/team/provider-icons.js', out);
console.log(`Wrote ${icons.length} provider icons`);
